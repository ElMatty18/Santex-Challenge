-- Users: one role per user. "user" is a reserved word, hence app_user.
CREATE TABLE app_user (
    id           VARCHAR(50)  NOT NULL PRIMARY KEY,
    display_name VARCHAR(100) NOT NULL,
    role         VARCHAR(20)  NOT NULL,
    CONSTRAINT ck_app_user_role CHECK (role IN ('ADMIN', 'REQUESTER', 'REVIEWER'))
);

-- Workflow states. Codes are identifiers with gaps, never compared to infer order.
CREATE TABLE workflow_state (
    code       INTEGER     NOT NULL PRIMARY KEY,
    name       VARCHAR(50) NOT NULL,
    is_initial BOOLEAN     NOT NULL,
    is_final   BOOLEAN     NOT NULL,
    CONSTRAINT uk_workflow_state_name UNIQUE (name)
);

-- Allowed transitions, one row per role. The only source of truth for allowed moves.
CREATE TABLE state_transition (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(50) NOT NULL,
    from_state   INTEGER     NOT NULL,
    to_state     INTEGER     NOT NULL,
    allowed_role VARCHAR(20) NOT NULL,
    CONSTRAINT fk_state_transition_from FOREIGN KEY (from_state) REFERENCES workflow_state (code),
    CONSTRAINT fk_state_transition_to FOREIGN KEY (to_state) REFERENCES workflow_state (code),
    CONSTRAINT ck_state_transition_role CHECK (allowed_role IN ('ADMIN', 'REQUESTER', 'REVIEWER')),
    CONSTRAINT uk_state_transition UNIQUE (code, from_state, to_state, allowed_role)
);

CREATE TABLE action (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(30)              NOT NULL,
    title        VARCHAR(120)             NOT NULL,
    description  VARCHAR(2000),
    state_code   INTEGER                  NOT NULL,
    requester_id VARCHAR(50)              NOT NULL,
    assignee_id  VARCHAR(50),
    outcome      VARCHAR(20),
    comment      VARCHAR(2000),
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version      BIGINT                   NOT NULL,
    CONSTRAINT fk_action_state FOREIGN KEY (state_code) REFERENCES workflow_state (code),
    CONSTRAINT fk_action_requester FOREIGN KEY (requester_id) REFERENCES app_user (id),
    CONSTRAINT fk_action_assignee FOREIGN KEY (assignee_id) REFERENCES app_user (id),
    CONSTRAINT ck_action_type CHECK (type IN ('EXPENSE_APPROVAL', 'DEPLOYMENT_REVIEW', 'DOCUMENT_UPLOAD', 'ONBOARDING')),
    CONSTRAINT ck_action_outcome CHECK (outcome IN ('APPROVED', 'REJECTED', 'DONE'))
);

-- Inbox queries: filter by visibility (requester / assignee) and state, oldest first.
CREATE INDEX ix_action_requester ON action (requester_id);
CREATE INDEX ix_action_assignee ON action (assignee_id);
CREATE INDEX ix_action_state_created ON action (state_code, created_at);

-- One row per changed field. No FK to action on purpose: audit does not depend on the
-- actions module, and could move to its own service.
CREATE TABLE audit_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_id  BIGINT                   NOT NULL,
    changed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    user_id    VARCHAR(50)              NOT NULL,
    field      VARCHAR(50)              NOT NULL,
    old_value  VARCHAR(2000),
    new_value  VARCHAR(2000),
    request_id VARCHAR(100)
);

CREATE INDEX ix_audit_log_action ON audit_log (action_id);
CREATE INDEX ix_audit_log_user_changed ON audit_log (user_id, changed_at);
CREATE INDEX ix_audit_log_changed ON audit_log (changed_at);
